def load() -> int:
    """Заливает библиотеку, проставляет предмет и подтему там, где их ещё нет."""
    added = 0
    for topic, skill, text, answer, options in LIBRARY:
        subject = SUBJECT_OF_TOPIC.get(topic)
        if db.q1("SELECT 1 FROM questions WHERE class_id IS NULL AND text = ?", text):
            continue
        db.run(
            "INSERT INTO questions (class_id, topic, text, answer, options, status, subject, skill)"
            " VALUES (NULL, ?, ?, ?, ?, 'approved', ?, ?)",
            topic, text, answer, "|".join(options), subject, skill,
        )
        added += 1

    # старые записи: три варианта и без подтемы - подтягиваем к нынешнему виду
    for topic, skill, text, answer, options in LIBRARY:
        db.run("UPDATE questions SET answer = ?, options = ?, skill = ? WHERE text = ?",
               answer, "|".join(options), skill, text)

    # старые вопросы заводились без предмета - дописываем по теме
    for topic, subject in SUBJECT_OF_TOPIC.items():
        db.run("UPDATE questions SET subject = ? WHERE topic = ?"
               " AND (subject IS NULL OR subject = '')", subject, topic)
    return added
