def from_bank() -> list[tuple]:
    """Вопросы из файлов bank/*.json - большие банки по темам."""
    out = []
    seen = {q[2] for q in LIBRARY}
    if not os.path.isdir(BANK_DIR):
        return out
    for name in sorted(os.listdir(BANK_DIR)):
        if not name.endswith(".json"):
            continue
        with open(os.path.join(BANK_DIR, name), encoding="utf-8") as f:
            data = json.load(f)
        topic = data["topic"]
        SUBJECT_OF_TOPIC.setdefault(topic, data.get("subject"))
        for q in data["questions"]:
            if q["text"] in seen:      # один и тот же вопрос в двух файлах - берём один раз
                continue
            seen.add(q["text"])
            out.append((topic, q.get("skill", ""), q["text"], q["answer"],
                        list(q["options"]), q.get("explanation", "")))
    return out


def all_questions() -> list[tuple]:
    return LIBRARY + from_bank()


def load() -> int:
    """Заливает библиотеку и подтягивает старые записи к нынешнему виду."""
    added = 0
    for topic, skill, text, answer, options, explanation in all_questions():
        subject = SUBJECT_OF_TOPIC.get(topic)
        if db.q1("SELECT 1 FROM questions WHERE class_id IS NULL AND text = ?", text):
            continue
        db.run(
            "INSERT INTO questions (class_id, topic, text, answer, options, status,"
            " subject, skill, explanation) VALUES (NULL, ?, ?, ?, ?, 'approved', ?, ?, ?)",
            topic, text, answer, "|".join(options), subject, skill, explanation,
        )
        added += 1

    # старые записи могли быть без подтемы, пояснения или с тремя вариантами
    for topic, skill, text, answer, options, explanation in all_questions():
        db.run("UPDATE questions SET answer = ?, options = ?, skill = ?, explanation = ?"
               " WHERE text = ?", answer, "|".join(options), skill, explanation, text)

    for topic, subject in SUBJECT_OF_TOPIC.items():
        db.run("UPDATE questions SET subject = ? WHERE topic = ?"
               " AND (subject IS NULL OR subject = '')", subject, topic)
    return added
