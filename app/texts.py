def plural(n: int, one: str, few: str, many: str) -> str:
    """5 вопросов, 2 вопроса, 1 вопрос."""
    n10, n100 = n % 10, n % 100
    if n10 == 1 and n100 != 11:
        form = one
    elif 2 <= n10 <= 4 and not 12 <= n100 <= 14:
        form = few
    else:
        form = many
    return f"{n} {form}"
